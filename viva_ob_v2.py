# --- Prevent a student from re-attempting the viva with the same link ---
def get_local_completed_rolls():
    """Returns the set of normalized Roll Numbers that already have a viva
    recorded in the LOCAL scoresheet on this running app instance. This
    resets if Streamlit Cloud restarts the app (a redeploy, or the container
    recycling after long inactivity) — kept only as an extra safety net
    alongside the durable Google Sheet check below.
    """
    if not os.path.exists(SCORESHEET_FILE):
        return set()
    try:
        with FileLock(SCORESHEET_LOCK, timeout=15):
            wb = load_workbook(SCORESHEET_FILE, read_only=True)
            ws = wb.active
            header_row = next(ws.iter_rows(min_row=1, max_row=1, values_only=True), ())
            if "Roll No" not in header_row:
                return set()
            roll_col = header_row.index("Roll No")
            rolls = set()
            for row in ws.iter_rows(min_row=2, values_only=True):
                value = row[roll_col] if roll_col < len(row) else None
                if value and str(value).strip():
                    rolls.add(str(value).strip().lower())
            return rolls
    except Exception:
        # Fail OPEN: an unreadable/locked scoresheet shouldn't itself block
        # a legitimate student from starting. Worst case here is a rare
        # missed duplicate, not the whole class getting locked out.
        return set()

@st.cache_data(ttl=20, show_spinner=False)
def get_remote_completed_rolls():
    """Reads the DURABLE list of Roll Numbers already recorded in the Google
    Sheet (via a GET request to the same Apps Script Web App the score
    webhook already posts to). Unlike the local file, this survives an app
    restart, so it's the authoritative check. Cached for a short window
    (20s) so every student's page render doesn't hit the Apps Script quota —
    a student who just finished may take up to ~20s to show up as blocked
    for someone else reloading the link, which is an acceptable trade-off.
    """
    webhook_url = st.secrets.get("GSHEETS_WEBHOOK_URL") or os.environ.get("GSHEETS_WEBHOOK_URL")
    if not webhook_url:
        return set()
    try:
        response = requests.get(webhook_url, timeout=10)
        data = response.json()
        return {str(r).strip().lower() for r in data.get("rolls", []) if r is not None and str(r).strip()}
    except Exception:
        # Fail OPEN here too: a network hiccup or a Sheet script that hasn't
        # been updated with the doGet handler yet shouldn't block students —
        # the local check below still catches same-session repeats.
        return set()

def get_completed_rolls():
    """Union of the durable Google Sheet record and the local scoresheet —
    a student is blocked if EITHER source already shows a completed viva
    for their Roll Number."""
    return get_local_completed_rolls() | get_remote_completed_rolls()

