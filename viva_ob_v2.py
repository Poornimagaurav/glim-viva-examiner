# Thresholds are the old /10 cutoffs (9, 8, 7, 6, 5) scaled up by 1.5x to the
# /15 scale, so the same proportion of the scale earns each grade as before.
def get_grade(score):
    if score is None:
        return "N/A"
    elif score >= 13.5:
        return "O (Outstanding)"
    elif score >= 12:
        return "A+ (Excellent)"
    elif score >= 10.5:
        return "A (Very Good)"
    elif score >= 9:
        return "B (Good)"
    elif score >= 7.5:
        return "C (Average)"
    else:
        return "F (Fail)"

