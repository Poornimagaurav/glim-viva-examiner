# --- Gemini model candidates ---
# Each student brings their OWN free Gemini API key (entered in the sidebar)
# instead of everyone sharing one faculty-managed key, so one student's
# usage can no longer rate-limit or block anyone else's viva.
#
# Google renames/retires model IDs faster than this file gets updated, and
# which exact models a given free-tier key can reach isn't something we can
# verify from here (the same lesson learned the hard way with a Groq model
# that 404'd despite being listed in Groq's own docs) — so instead of
# betting on one hardcoded name, we try each of these in order and stick
# with the first one that actually works for THAT student's key. If every
# candidate 404s, check https://aistudio.google.com/ while signed into the
# affected Google account for a model name it can actually reach, and add
# it to this list.
GEMINI_MODEL_CANDIDATES = [
    "gemini-2.5-flash",
    "gemini-2.0-flash",
    "gemini-2.5-flash-lite",
]

def _to_gemini_contents(messages):
    """Converts our internal OpenAI-style [{"role", "content"}, ...] history
    into Gemini's shape: a separate system_instruction string, plus a
    contents list of genai_types.Content (role "user" or "model")."""
    system_instruction = None
    contents = []
    for m in messages:
        if m["role"] == "system":
            # Only one system message exists in this app; if that ever
            # changes, later ones would overwrite earlier ones here.
            system_instruction = m["content"]
        else:
            role = "model" if m["role"] == "assistant" else "user"
            contents.append(genai_types.Content(
                role=role, parts=[genai_types.Part.from_text(text=m["content"])]
            ))

    if not contents:
        # The very first call of a viva has ONLY the system message so far
        # (the opening greeting hasn't been generated yet) — unlike Groq/
        # OpenAI-style chat APIs, Gemini rejects an empty `contents` list
        # outright ("contents are required"), so give it a minimal kickoff
        # turn. The system prompt already ends with an explicit instruction
        # to begin by greeting the student, so this just triggers that.
        contents.append(genai_types.Content(
            role="user", parts=[genai_types.Part.from_text(text="Begin the viva now.")]
        ))
    return system_instruction, contents

def chat_with_llm(messages, max_retries=5):
    """Calls the Gemini API with the CURRENT STUDENT'S OWN key, retrying
    transient/rate-limit errors with backoff and falling back through
    GEMINI_MODEL_CANDIDATES on a "model not found" response. Only gives up
    (with a friendly message, plus the real error for troubleshooting) once
    every avenue is exhausted.
    """
    api_key = (st.session_state.get("gemini_api_key") or "").strip()
    if not api_key:
        st.error("⚠️ Enter your Gemini API key in the sidebar before starting the viva.")
        return None

    client = genai.Client(api_key=api_key)
    system_instruction, contents = _to_gemini_contents(messages)
    config = genai_types.GenerateContentConfig(
        system_instruction=system_instruction,
        max_output_tokens=1024,
        temperature=0.4,
    )

    # Once we've found a model THIS key can reach, keep using it for the
    # rest of the viva instead of re-probing every candidate on every call.
    models_to_try = (
        [st.session_state["gemini_working_model"]]
        if st.session_state.get("gemini_working_model")
        else GEMINI_MODEL_CANDIDATES
    )

    last_error = None
    for model_name in models_to_try:
        for attempt in range(max_retries):
            try:
                response = client.models.generate_content(
                    model=model_name, contents=contents, config=config,
                )
                st.session_state.gemini_working_model = model_name
                return response.text
            except Exception as e:
                last_error = e
                msg = str(e).lower()

                if any(tok in msg for tok in
                       ["api key not valid", "api_key_invalid", "permission_denied",
                        "401", "403"]):
                    st.error(
                        "⚠️ Your Gemini API key was rejected. Double-check you pasted "
                        "it correctly, or get a fresh free key at "
                        "https://aistudio.google.com/apikey."
                    )
                    return None

                if any(tok in msg for tok in ["404", "not found", "does not exist"]):
                    # This model isn't reachable on this key — try the next
                    # candidate instead of burning retries on a dead end.
                    break

                if any(tok in msg for tok in
                       ["400", "invalid_argument", "invalid argument"]):
                    # A malformed request (e.g. once, an empty `contents`
                    # list on the very first call). Retrying won't help —
                    # the exact same request would just fail the exact same
                    # way — so say so plainly instead of the misleading
                    # "temporarily busy, try again" message, which would
                    # send a student into a pointless retry loop.
                    st.error(
                        "⚠️ The examiner AI rejected this request as malformed — "
                        "this points to a bug in the app rather than something "
                        "retrying will fix. Please tell your faculty, including "
                        "the technical details below."
                    )
                    with st.expander("Technical details (for troubleshooting)"):
                        st.code(str(last_error))
                    return None

                is_transient = any(tok in msg for tok in
                                    ["429", "resource_exhausted", "rate limit", "quota",
                                     "timeout", "timed out", "502", "503", "unavailable",
                                     "connection"])
                if is_transient and attempt < max_retries - 1:
                    # Exponential backoff with jitter.
                    wait = (2 ** attempt) + random.uniform(0, 1)
                    time.sleep(wait)
                    continue

                # A non-transient, non-404 error, or retries exhausted on a
                # transient one: give up rather than silently cycling every
                # remaining candidate model.
                st.error(
                    "⚠️ The examiner AI is temporarily busy or rate-limited. Please "
                    "wait a few seconds, then submit your answer again — nothing "
                    "has been lost."
                )
                with st.expander("Technical details (for troubleshooting)"):
                    st.code(str(last_error))
                return None

    st.error(
        "⚠️ None of the expected Gemini models "
        f"({', '.join(GEMINI_MODEL_CANDIDATES)}) are available on your API key. "
        "Check https://aistudio.google.com/ while signed into the Google account "
        "the key belongs to, for a model name it can access."
    )
    with st.expander("Technical details (for troubleshooting)"):
        st.code(str(last_error))
    return None

# --- Save to Google Sheets via Webhook ---
def save_to_google_sheets(student_name, student_roll, student_email, subject, difficulty, score,
                          grade, strengths, improvements, exchanges, project_name):
    """Posts one row to the Google Sheet webhook. Returns (success, message)
    instead of calling st.error/st.warning directly — those calls only ever
    render on the ONE script rerun where this function happens to execute;
    on every later rerun of the same "viva ended" screen, Streamlit doesn't
    replay them, so a real error can flash for a moment and then vanish
    before anyone reads it. The caller stores the returned message in
    st.session_state and re-displays it on every rerun instead, so a
    misconfiguration is actually visible rather than silently disappearing.
    """
    webhook_url = st.secrets.get("GSHEETS_WEBHOOK_URL") or os.environ.get("GSHEETS_WEBHOOK_URL")
    if not webhook_url:
        return False, (
            "Google Sheets NOT saved: the GSHEETS_WEBHOOK_URL secret is missing or empty. "
            "In Streamlit -> Settings -> Secrets add a line exactly like:  "
            'GSHEETS_WEBHOOK_URL = "https://script.google.com/macros/s/XXX/exec"  '
            "then Save and Reboot."
        )
    if not str(webhook_url).strip().endswith("/exec"):
        return False, (
            "Your GSHEETS_WEBHOOK_URL does not end in /exec. Use the Apps Script Web App "
            "URL from Deploy -> Web app, not the editor or /dev URL."
        )

    payload = {
        "student_name": student_name,
        "student_roll": student_roll,
        "student_email": student_email,
        "subject": subject,
        "difficulty": difficulty,
        "project_name": project_name,
        "score": score,
        "grade": grade,
        "exchanges": exchanges,
        "strengths": strengths,
        "improvements": improvements
    }

    try:
        response = requests.post(webhook_url, json=payload, timeout=15)
        if response.status_code == 200 and "Success" in response.text:
            return True, "📊 Score successfully posted to Google Sheets!"
        else:
            return False, (
                "Google Sheets did not accept the data (HTTP "
                + str(response.status_code) + "). Response start: "
                + str(response.text)[:300]
                + "  ->  Most likely the Apps Script Web App access is not set to "
                "'Anyone', or you edited the script without deploying a NEW version."
            )
    except Exception as e:
        return False, f"⚠️ Failed to write to Google Sheets: {e}"

# --- Extract text from uploaded file ---
def extract_text(uploaded_file):
    text = ""
    if uploaded_file.name.endswith(".pdf"):
        pdf_bytes = uploaded_file.read()
        doc = fitz.open(stream=pdf_bytes, filetype="pdf")
        for page in doc:
            text += page.get_text()
    elif uploaded_file.name.endswith(".docx"):
        doc = Document(io.BytesIO(uploaded_file.read()))
        for para in doc.paragraphs:
            text += para.text + "\n"
    return text.strip()

